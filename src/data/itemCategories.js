const seedItemCategoryLookup = new Map();

Object.entries(seedItemsByCategory).forEach(([category, itemNames]) => {
  itemNames.forEach((itemName) => {
    seedItemCategoryLookup.set(normalizeItemKey(itemName), category);
  });
});

export function isSeedCategoryHeader(value) {
  return seedCategoryHeaders.has(String(value ?? "").trim().toUpperCase());
}

export function normalizeItemCategory(value, fallback = DEFAULT_ITEM_CATEGORY) {
  const normalizedKey = normalizeCategoryKey(value);
  if (!normalizedKey) return fallback;

  return categoryAliases.get(normalizedKey) ?? fallback;
}

export function getSeedItemCategory(itemName, fallback = DEFAULT_ITEM_CATEGORY) {
  return seedItemCategoryLookup.get(normalizeItemKey(itemName)) ?? fallback;
}

export function resolvePreferredItemCategory(itemName, currentCategory, fallback = DEFAULT_ITEM_CATEGORY) {
  const normalizedCategory = normalizeItemCategory(currentCategory, "");
  const seedCategory = getSeedItemCategory(itemName, "");

  if (
    seedCategory &&
    (!normalizedCategory ||
      normalizedCategory === DEFAULT_ITEM_CATEGORY ||
      isSeedCategoryHeader(currentCategory))
  ) {
    return seedCategory;
  }

  return normalizedCategory || seedCategory || fallback;
}
