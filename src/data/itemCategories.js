function normalizeCategoryKey(value) {
  return String(value ?? "")
    .trim()
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[\/,.-]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function normalizeItemKey(value) {
  return String(value ?? "").trim().toUpperCase();
}

